-- Sistema para Venta de Computadoras
-- Script 01: definicion de tablas (DDL)
-- Motor: PostgreSQL 14 o superior
--
-- Este script elimina las tablas si ya existen y las vuelve a crear.
-- Ejecutarlo borra todos los datos del esquema.
-- Orden de ejecucion: 01_ddl.sql, 02_dml.sql, 03_consultas.sql.

SET client_min_messages TO WARNING;

BEGIN;

DROP TABLE IF EXISTS detalle_venta;
DROP TABLE IF EXISTS ventas;
DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS clientes;
DROP TABLE IF EXISTS proveedores;

CREATE TABLE proveedores (
    id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(120) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    correo VARCHAR(120) NOT NULL,
    CONSTRAINT pk_proveedores PRIMARY KEY (id_proveedor),
    CONSTRAINT uq_proveedores_correo UNIQUE (correo),
    CONSTRAINT chk_proveedores_nombre CHECK (char_length(trim(nombre)) > 0),
    CONSTRAINT chk_proveedores_telefono CHECK (char_length(trim(telefono)) > 0),
    CONSTRAINT chk_proveedores_correo CHECK (
        correo ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    )
);

CREATE TABLE productos (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(80) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    precio NUMERIC(10, 2) NOT NULL,
    stock INTEGER NOT NULL,
    id_proveedor INTEGER NOT NULL,
    CONSTRAINT pk_productos PRIMARY KEY (id_producto),
    CONSTRAINT fk_productos_proveedor FOREIGN KEY (id_proveedor)
        REFERENCES proveedores (id_proveedor)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_productos_nombre CHECK (char_length(trim(nombre)) > 0),
    CONSTRAINT chk_productos_marca CHECK (char_length(trim(marca)) > 0),
    CONSTRAINT chk_productos_categoria CHECK (char_length(trim(categoria)) > 0),
    CONSTRAINT chk_productos_precio CHECK (precio > 0),
    CONSTRAINT chk_productos_stock CHECK (stock >= 0)
);

CREATE INDEX idx_productos_id_proveedor ON productos (id_proveedor);

CREATE TABLE clientes (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    documento VARCHAR(20) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    CONSTRAINT pk_clientes PRIMARY KEY (id_cliente),
    CONSTRAINT uq_clientes_documento UNIQUE (documento),
    CONSTRAINT chk_clientes_nombre CHECK (char_length(trim(nombre)) > 0),
    CONSTRAINT chk_clientes_documento CHECK (documento ~ '^[0-9]{8,12}$'),
    CONSTRAINT chk_clientes_telefono CHECK (char_length(trim(telefono)) > 0)
);

CREATE TABLE ventas (
    id_venta INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INTEGER NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_ventas PRIMARY KEY (id_venta),
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (id_cliente)
        REFERENCES clientes (id_cliente)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_ventas_total CHECK (total >= 0)
);

CREATE INDEX idx_ventas_id_cliente ON ventas (id_cliente);

CREATE TABLE detalle_venta (
    id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_venta INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10, 2) NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_detalle_venta PRIMARY KEY (id_detalle),
    CONSTRAINT uq_detalle_venta_producto UNIQUE (id_venta, id_producto),
    CONSTRAINT fk_detalle_venta_venta FOREIGN KEY (id_venta)
        REFERENCES ventas (id_venta)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_venta_producto FOREIGN KEY (id_producto)
        REFERENCES productos (id_producto)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_detalle_precio CHECK (precio_unitario > 0),
    CONSTRAINT chk_detalle_subtotal CHECK (subtotal = cantidad * precio_unitario)
);

CREATE INDEX idx_detalle_venta_id_venta ON detalle_venta (id_venta);
CREATE INDEX idx_detalle_venta_id_producto ON detalle_venta (id_producto);

COMMIT;
